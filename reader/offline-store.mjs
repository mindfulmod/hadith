import {verifyResponse} from './integrity.mjs';
const RECEIPT='x-hadith-verified-sha256';
export const releaseModuleSource=release=>'// Generated by build-release.mjs.\nexport const release = '+JSON.stringify(release,null,2)+';\n';
export const readerCacheName=release=>'hadith-reader-'+release.id;
export const olderReaderCaches=(names,current)=>names.filter(name=>/^hadith-reader-opening-[0-9a-f]{12}$/.test(name)&&name!==current).reverse();
const fault=(code,message=code)=>Object.assign(new Error(message),{code});
export function verifiedCopy(response,file){
 const headers=new Headers(response.headers);headers.set(RECEIPT,file.sha256);headers.set('Content-Length',String(file.bytes));headers.delete('Content-Encoding');
 return new Response(response.body,{status:200,headers});
}
export function validatePacks(release){
 const files=new Map(release.files.map(f=>[f.path,f])),packs=new Map(),owned=new Set();
 if(files.size!==release.files.length)throw fault('manifest');
 for(const pack of release.packs||[]){
  if(!/^[a-z0-9-]+$/.test(pack.id)||packs.has(pack.id)||!pack.files.length)throw fault('manifest');
  packs.set(pack.id,pack);
  for(const path of pack.files){if(!files.has(path)||owned.has(path))throw fault('manifest');owned.add(path);}
  if(pack.bytes!==pack.files.reduce((sum,path)=>sum+files.get(path).bytes,0))throw fault('manifest');
 }
 if(owned.size!==files.size||packs.get('reading')?.kind!=='reading')throw fault('manifest');
 const visiting=new Set(),done=new Set();
 function visit(id){if(visiting.has(id)||!packs.has(id))throw fault('manifest');if(done.has(id))return;visiting.add(id);for(const dep of packs.get(id).requires||[])visit(dep);visiting.delete(id);done.add(id);}
 for(const id of packs.keys())visit(id);
 if(packs.get('reading').files.some(p=>files.get(p).audio))throw fault('manifest');
 return {files,packs};
}

// The active worker owns this store, serializing all tabs' save/remove requests.
// Readiness receipts mean bytes passed SHA-256 at write time; Check downloads
// reads and hashes saved bytes again. Presence is checked on every inspection.
export function createOfflineStore({release,base,cacheStorage=globalThis.caches,fetcher=globalThis.fetch,notify=()=>{},idleTimeout=30000}){
 const {files,packs}=validatePacks(release),name=readerCacheName(release),url=path=>new URL(path,base).href;
 let operation=null,controller=null,last=null;
 const emit=()=>notify({release:release.id,operation:operation?{...operation}:null,packs:last?.packs||[],oldVersions:last?.oldVersions||0});
 const stopped=()=>{if(controller?.signal.aborted)throw fault('cancelled');};
 function plan(id){const result=[],seen=new Set();function add(key){const pack=packs.get(key);if(!pack)throw fault('unknown-pack');if(seen.has(key))return;seen.add(key);for(const dep of pack.requires||[])add(dep);result.push(pack);}add(id);return result;}
 async function inspect({deep=false}={}){
  const cache=await cacheStorage.open(name),states=[];
  const manifest=await cache.match(url('release.mjs'));
  const manifestReady=!!manifest&&manifest.status===200&&await manifest.text()===releaseModuleSource(release);
  for(const pack of packs.values()){
   let saved=0,bytes=0;
   for(const path of pack.files){
    if(deep)stopped();const file=files.get(path),response=await cache.match(url(path));if(!response)continue;
    let valid=response.status===200&&response.headers.get(RECEIPT)===file.sha256&&Number(response.headers.get('Content-Length'))===file.bytes;
    if(deep){let intact=false;try{await verifyResponse(response,file);intact=true;}catch{await cache.delete(url(path));}if(intact&&!valid)await cache.put(url(path),verifiedCopy(response.clone(),file));valid=intact;}
    if(valid){saved++;bytes+=file.bytes;}
   }
   states.push({id:pack.id,filesSaved:saved,totalFiles:pack.files.length,bytesSaved:bytes,bytes:pack.bytes,state:saved===pack.files.length?'ready':saved?'partial':'absent'});
  }
  const byId=new Map(states.map(s=>[s.id,s]));
  function available(id){return manifestReady&&byId.get(id).state==='ready'&&(packs.get(id).requires||[]).every(available);}
  for(const state of states)state.ready=available(state.id);
  last={release:release.id,manifestReady,operation:operation?{...operation}:null,packs:states,oldVersions:olderReaderCaches(await cacheStorage.keys(),name).length};
  return last;
 }
 async function download(file){
  const local=new AbortController();let timer,reader;
  const reset=()=>{clearTimeout(timer);timer=setTimeout(()=>local.abort(fault('timeout')),idleTimeout);};
  const abort=()=>local.abort(fault('cancelled'));
  controller.signal.addEventListener('abort',abort,{once:true});reset();
  try{
   const response=await fetcher(url(file.path),{cache:'reload',signal:local.signal});
   if(response.status!==200)throw fault('download');
   const chunks=[];let received=0,lastProgress=0;
   if(response.body?.getReader){
    reader=response.body.getReader();
    for(;;){const {done,value}=await reader.read();if(done)break;stopped();reset();received+=value.byteLength;if(received>file.bytes)throw fault('integrity');chunks.push(value);operation.fileBytes=received;if(Date.now()-lastProgress>200){lastProgress=Date.now();emit();}}
   }else{const value=new Uint8Array(await response.arrayBuffer());chunks.push(value);received=value.byteLength;}
   clearTimeout(timer);stopped();
   const complete=new Response(new Blob(chunks),{status:200,headers:response.headers});
   try{await verifyResponse(complete,file);}catch{throw fault('integrity');}
   return verifiedCopy(complete,file);
  }catch(error){if(controller.signal.aborted)throw fault('cancelled');if(local.signal.aborted)throw fault('timeout');throw typeof error.code==='string'?error:fault('download');}
  finally{clearTimeout(timer);controller.signal.removeEventListener('abort',abort);reader?.cancel().catch(()=>{});}
 }
 async function save(id){
  const cache=await cacheStorage.open(name),wanted=plan(id).flatMap(p=>p.files),old=olderReaderCaches(await cacheStorage.keys(),name);
  operation.totalFiles=wanted.length;operation.totalBytes=wanted.reduce((sum,path)=>sum+files.get(path).bytes,0);operation.doneBytes=0;operation.doneFiles=0;
  for(const path of wanted){
   stopped();const file=files.get(path);operation.path=path;operation.fileBytes=0;emit();let response=await cache.match(url(path)),valid=false;
   if(response){try{await verifyResponse(response,file);valid=true;}catch{await cache.delete(url(path));}}
   if(!valid){
    for(const previous of old){stopped();const candidate=await (await cacheStorage.open(previous)).match(url(path));if(!candidate)continue;try{await verifyResponse(candidate,file);response=candidate;valid=true;break;}catch{}}
   }
   stopped();if(!valid)response=await download(file);
   stopped();await cache.put(url(path),verifiedCopy(response,file));operation.doneFiles++;operation.doneBytes+=file.bytes;operation.fileBytes=0;emit();
  }
  // Reconstruct only the already-loaded, exact release metadata; never substitute
  // a later network manifest into this worker's bundle.
  stopped();await cache.put(url('release.mjs'),new Response(releaseModuleSource(release),{headers:{'Content-Type':'text/javascript'}}));
 }
 async function run(action,id){
  if(operation)throw fault('busy');
  if(!['save','check','remove','cleanup'].includes(action))throw fault('unknown-action');
  if(action==='save')plan(id);
  if(action==='remove'&&(!packs.has(id)||packs.get(id).kind==='reading'))throw fault('protected-reading');
  operation={action,packId:id||null};controller=new AbortController();emit();let error;
  try{
   if(action==='save')await save(id);
   if(action==='check')await inspect({deep:true});
   if(action==='remove'){const cache=await cacheStorage.open(name);for(const path of packs.get(id).files){stopped();await cache.delete(url(path));}}
   if(action==='cleanup')for(const previous of olderReaderCaches(await cacheStorage.keys(),name)){stopped();await cacheStorage.delete(previous);}
  }catch(caught){error=typeof caught.code==='string'?caught:fault(caught.name==='QuotaExceededError'?'quota':'storage',caught.message);}
  finally{operation=null;controller=null;try{await inspect();}catch{last=null;}emit();}
  if(error)throw error;
  return last;
 }
 return {inspect:async()=>operation?{...last,release:release.id,operation:{...operation}}:inspect(),run,cancel(){controller?.abort();},get busy(){return !!operation;},get state(){return {...last,release:release.id,operation:operation?{...operation}:null};}};
}
